## NEW: This is adapted from nCompiler's nfMethodRC
## NF_InternalsClass combines nfMethodRCinterface and nfMethodRC,
## unless we re-encounter a need to separate them.
NF_InternalsClass <- R6::R6Class(
  classname = "NF_InternalsClass",
  portable = FALSE,
  public = list(
    arguments = NULL, # formals as written, i.e. with type declarations
    Rarguments = NULL, # formals with defaults (or nothing) in place of type declarations
    argDefaults = NULL, # named list of default expressions, for args that have them
    argDefaultDeps = NULL, # named list: for each arg with a default, the arg names it uses
    argDefaultOrder = NULL, # names of args with defaults, in evaluation order
    refArgs = NULL,
    blockRefArgs = NULL,
    argSymTab = NULL,
    returnSym = NULL,
    control = list(),
    where = NULL,
    # isMethod = FALSE,
    uniqueName = character(),
    uniqueName2 = character(),
    # cpp_code_name = character(),
    cpp_code_name = character(),
    ## template = NULL, replaced with default_matchDef
    default_matchDef = NULL,
    code = NULL,
    RcppPacket = NULL,
    Rwrapper = NULL,
    aux = NULL, ## Used for constructor initializers.
    # needed_nFunctions = list(), ## formerly neededRCfuns
    ADcontent = NULL,
    isAD = FALSE,
    predefined = FALSE, # Location for reading and (default) writing predefined nFunction saved RcppPacket. Writing location can be over-ridden by compileInfo$predefined_output_dir
    compileInfo = list(),
    R_fun = NULL, # used only if compileInfo$C_fun is provided.
    ## Next two "includes" were only needed for making external calls:
    ## If needed, these will be populated by nCompilerExternalCall.
    ## It remains to be seen if they are needed in new system.
    externalHincludes = list(),
    externalCPPincludes = list(),
    initialize = function(fun, ## formerly method
                          name,
                          argTypes = list(),
                          refArgs = list(),
                          blockRefArgs = list(),
                          returnType = NULL,
                          enableDerivs = FALSE,
                          control = list(),
                          compileInfo = list(),
                          predefined = FALSE,
                          ## methodNames, ## used only for nf_checkDSLcode
                          ## setupVarNames = NULL, ## Ditto
                          where = parent.frame()) {
      ## name is required and is generated by NF() if not provided.
      ## uniqueName is only needed if this is not a method of a nClass.
      TreturnType <- nCaptureType(returnType)
      if (!missing(name)) {
        self$uniqueName <- name
        self$uniqueName2 <- paste(name,
          nFunctionIDMaker(),
          sep = "_"
        )
      } else {
        stop("NF_InternalsClass needs a name argument.", call. = FALSE)
      }
      ## uniqueName2 is needed even for methods, to serve as unique keys.
      if (is.null(compileInfo$C_fun)) {
        fun_to_use <- fun
      } else {
        self$R_fun <- fun
        ## Check that fun and C_fun agree on argument names and order,
        ## up to the number of arguments in C_fun.  fun may have additional
        ## arguments beyond those (e.g. for uncompiled-only bookkeeping).
        c_arg_names <- names(formals(compileInfo$C_fun))
        r_arg_names <- names(formals(fun))
        n_c <- length(c_arg_names)
        n_r <- length(r_arg_names)
        if (n_r < n_c) {
          stop(
            paste0(
              "In nFunction '", self$uniqueName, "': fun has ", n_r,
              " argument(s) but compileInfo$C_fun has ", n_c,
              ". fun must have at least as many arguments as C_fun,",
              " in the same order."
            ),
            call. = FALSE
          )
        }
        mismatches <- which(r_arg_names[seq_len(n_c)] != c_arg_names)
        if (length(mismatches) > 0) {
          stop(
            paste0(
              "In nFunction '", self$uniqueName, "': argument name mismatch between",
              " fun and compileInfo$C_fun at position(s) ",
              paste(mismatches, collapse = ", "), ". ",
              "fun: (", paste(r_arg_names[seq_len(n_c)], collapse = ", "), "); ",
              "C_fun: (", paste(c_arg_names, collapse = ", "), ")."
            ),
            call. = FALSE
          )
        }
        fun_to_use <- compileInfo$C_fun
      }
      if (!is.null(compileInfo$initializers)) {
        self$aux <- list(initializerList = compileInfo$initializers)
      }
      self$arguments <- as.list(formals(fun_to_use))
      self$control <- control
      self$compileInfo <- compileInfo
      self$predefined <- predefined
      self$compileInfo$C_fun <- NULL # Do not retain this because it ends up in code and arguments
      self$where <- where
      if (is.character(refArgs)) {
        refArgs <- structure(as.list(rep(TRUE, length(refArgs))),
          names = refArgs
        )
      }
      self$refArgs <- refArgs
      if (is.character(blockRefArgs)) {
        blockRefArgs <- structure(as.list(rep(TRUE, length(blockRefArgs))),
          names = blockRefArgs
        )
      }
      self$blockRefArgs <- blockRefArgs
      self$argSymTab <- typeList2symbolTable(
        typeList = arguments,
        isArg = rep(TRUE, length(arguments)),
        isRef = refArgs,
        isBlockRef = blockRefArgs,
        explicitTypeList = argTypes,
        where = where
      )
      ## Defaults from type declarations, e.g. x = double(1, default = 1:5).
      ## This uses only this nFunction's own declarations.
      defaultsInfo <- NF_processArgDefaults(
        arguments = arguments,
        argSymTab = self$argSymTab,
        explicitArgNames = names(argTypes),
        fnName = name
      )
      self$Rarguments <- defaultsInfo$Rarguments
      self$argDefaults <- defaultsInfo$argDefaults
      self$argDefaultDeps <- defaultsInfo$argDefaultDeps
      self$argDefaultOrder <- defaultsInfo$argDefaultOrder
      ## nf_changeKeywords changes all nCompiler keywords,
      ## e.g. 'print' to 'nPrint'; see 'nKeyWords' list in
      ## changeKeywords.R
      self$code <- body(fun_to_use)
      if (self$code[[1]] != "{") {
        self$code <- substitute(
          {
            CODE
          },
          list(CODE = self$code)
        )
      }
      ## The matchDef uses Rarguments so that defaults (not type declarations)
      ## are filled in for missing arguments by normalizeCalls.
      self$default_matchDef <- Rarguments_2_function(Rarguments, body = quote({})) ## generateTemplate()
      returnTypeInfo <- nf_extractReturnType(code)
      returnTypeDecl <- returnTypeInfo$returnType
      returnArgNull <- is.null(rlang::quo_get_expr(TreturnType))
      if (is.null(returnTypeDecl)) {
        if (returnArgNull) {
          TreturnType <- nType(void())
        }
      } else {
        if (!returnArgNull) {
          stop(
            paste0(
              "Return type for ", name, " was declared in code and by returnType argument.\n",
              "Use one or the other.  Providing both is not allowed.\n"
            ),
            call. = FALSE
          )
        }
        TreturnType <- nType(expr = returnTypeDecl, env = where)
        self$code <- returnTypeInfo$code ## with returnType() line stripped
      }
      self$returnSym <- type2symbol({{ TreturnType }},
        origName = "returnType",
        where = where
      )

      # It is important to do this after getting the returnType info
      # because this will change integer to nInteger, even in returnType
      if (isTRUE(control$changeKeywords)) {
        self$code <- nf_changeKeywords(self$code)
      }

      ## We set the cpp_code_name here so that other nFunctions
      ## that call this one can determine, during compilation,
      ## what this one's cpp function name will be.
      ## However, if this nFunction is used as a method of a nClass,
      ## and if that nClass inherits from another nClass and this
      ## nFunction is actually virtual, then the base class's
      ## cpp_code_name will be used instead.
      ## However, we do not modify it in this NFinternals because
      ## it is permitted to use this elsewhere, e.g. on its own
      ## or to provide a method to a different nClass.
      if (!is.null(compileInfo$cpp_code_name)) {
        # self$cpp_code_name <- compileInfo$cpp_code_name
        self$cpp_code_name <- compileInfo$cpp_code_name
      } else {
        # self$cpp_code_name <- Rname2CppName(name)
        self$cpp_code_name <- Rname2CppName(name)
        # do not uniquify cpp_code_name
        # if(isFALSE(predefined))
        #   self$cpp_code_name <- paste(self$cpp_code_name,
        #                               nFunctionIDMaker(),
        #                               sep = "_")
      }
      ## Unpack enableDerivs into AD
      self$isAD <- FALSE
      if (!(isFALSE(enableDerivs) || is.null(enableDerivs))) {
        if (isTRUE(enableDerivs)) enableDerivs <- list()
        if (!is.list(enableDerivs)) {
          stop("enableDerivs must be NULL, FALSE, TRUE, or a list.")
        }
        if (isTRUE(enableDerivs$isAD)) {
          self$isAD <- TRUE
          self$compileInfo$callFromR <- FALSE
        } else {
          self$ADcontent <- list()
          self$ADcontent$ADfun <- enableDerivs$ADfun
          self$ADcontent$ignore <- enableDerivs$ignore
          # to-do: process types. make and AD__() function that returns ADfun from an nFunctionClass
          self$ADcontent$cpp_code_name <- paste0(cpp_code_name, "_AD__")
        }
      }
      # Check on virtual and abstract
      if (isTRUE(self$compileInfo$abstract)) {
        if (!isTRUE(self$compileInfo$virtual)) {
          warning("Setting compileInfo$virtual = TRUE since compileInfo$abstract = TRUE")
        }
        self$compileInfo$virtual <- TRUE
      }
    },
    updateCode = function(newCode) {
      self$code <- newCode
      if (self$code[[1]] != "{") {
        self$code <- substitute(
          {
            CODE
          },
          list(CODE = self$code)
        )
      }
      if (isTRUE(self$control$changeKeywords)) {
        self$code <- nf_changeKeywords(self$code)
      }
    },
    getFunction = function() {
      # functionAsList <- list(as.name('function'))
      # functionAsList[2] <- list(NULL)
      callableCode <- if (!is.null(self$R_fun)) {
        body(self$R_fun)
      } else {
        self$code
      }
      # if(!is.null(arguments)) functionAsList[[2]] <- as.pairlist(arguments)
      # callableCode <- code_to_use
      if (isTRUE(control$updateArgPassing)) {
        boolRefArg <- unlist(lapply(
          argSymTab$symbols,
          function(x) x$isRef
        ))
        refArgs <- names(argSymTab$symbols)[boolRefArg]
        boolBlockRefArg <- unlist(lapply(
          argSymTab$symbols,
          function(x) x$isBlockRef
        ))
        blockRefArgs <- names(argSymTab$symbols)[boolBlockRefArg]
        if (length(refArgs) > 0 | length(blockRefArgs) > 0) {
          callableCode <- passByReference(
            callableCode,
            refArgs,
            blockRefArgs
          )
        }
      }
      #      functionAsList[[3]] <- callableCode
      #      ans <- eval(
      #        parse(text=deparse(as.call(functionAsList)),
      #              keep.source = FALSE)[[1]])
      ans <- Rarguments_2_function(Rarguments, callableCode)
      environment(ans) <- where
      ans
    }
  )
)

Rarguments_2_function <- function(Rarguments, body = quote({})) {
  functionAsList <- list(as.name("function"))
  functionAsList[2] <- list(NULL)
  if (!is.null(Rarguments)) functionAsList[[2]] <- as.pairlist(Rarguments)
  functionAsList[[3]] <- body
  # eval(as.call(functionAsList))
  eval(
    parse(
      text = deparse(as.call(functionAsList)),
      keep.source = FALSE
    )[[1]]
  )
}

nf_extractReturnType <- function(code) {
  returnLineNum <- 0
  for (i in seq_along(code)) {
    if (length(code[[i]]) > 1) {
      if (is.name(code[[i]][[1]])) {
        if (code[[i]][[1]] == "returnType") {
          returnLineNum <- i
          break
        }
      }
    }
  }
  if (sum(all.names(code) == "returnType") > 1) {
    stop("multiple returnType() declarations in nFunction method; only one allowed")
  }
  if (returnLineNum == 0) {
    ## no returnType() declaration was found;
    ## create default behavior.
    returnTypeDeclaration <- NULL ## quote(void())
  } else {
    ## returnType() declaration was found
    returnTypeDeclaration <- code[[returnLineNum]][[2]]
    code[returnLineNum] <- NULL
  }
  ## a very patchy solution: switch nInteger back to integer
  ## if(as.character(returnTypeDeclaration[[1]]) == 'nInteger')
  ##     returnTypeDeclaration[[1]] <- as.name('integer')
  ## if(as.character(returnTypeDeclaration[[1]]) == 'nLogical')
  ##     returnTypeDeclaration[[1]] <- as.name('logical')
  list(
    code = code,
    returnType = returnTypeDeclaration
  )
}

# Set arguments (formals) for an R function that calls a compiled 
# nFunction or method. (We call this R function an interface.)
#
# These are taken from the original nFunction definition,
# except that ref, blockRef, and nClass arguments get no default.
# 
# For ref and blockRef, there would be no object to reference.
#
# For nClass, the default would be an uncompiled object.
#
# Both might be subject to future support.
NF_compiledRformals <- function(NFinternals) {
  Rarguments <- NFinternals$Rarguments
  if (is.null(Rarguments)) {
    return(NULL)
  }
  argSymTab <- NFinternals$argSymTab
  # refArgs and blockRefArgs may be named logical lists or character vectors
  isListed <- \(args, nm) if (is.list(args)) isTRUE(args[[nm]]) else nm %in% args
  for (nm in names(Rarguments)) {
    if (is.blank(Rarguments[[nm]])) next
    sym <- argSymTab$getSymbol(nm)
    noDefault <- isListed(NFinternals$refArgs, nm) ||
      isListed(NFinternals$blockRefArgs, nm) ||
      isTRUE(sym$isRef) || isTRUE(sym$isBlockRef) ||
      inherits(sym, c("symbolTBD", "symbolNC"))
    if (noDefault) Rarguments[nm] <- list(quote(expr = ))
  }
  as.pairlist(Rarguments)
}

# This takes the R function that calls a compiled nFunction and sets its argument defaults.
# This wrapper function comes from Rcpp.
# If argument names do not all match (potentially due to name mangling?),
# fun is returned unchanged.
NF_setCompiledRdefaults <- function(fun, NFinternals) {
  newFormals <- NF_compiledRformals(NFinternals)
  if (is.null(newFormals)) {
    return(fun)
  }
  if (!identical(names(formals(fun)), names(newFormals))) {
    return(fun)
  }
  formals(fun) <- newFormals
  fun
}

# Process defaults from argument type declarations,
# e.g. function(x = double(1, default = 1:5), y = double(1, default = 1 / x)).
#
# Returns:
#   Rarguments: formals with the default (or nothing) in place of each type
#     declaration. These are used for the uncompiled R function and for the
#     default_matchDef, so normalizeCalls fills in defaults (not declarations).
#     For an argument whose type is given in argTypes, the formal is kept as
#     written (preserving prior behavior).
#   argDefaults: named list of default expressions.
#   argDefaultDeps: named list giving, for each argument with a default, the
#     other arguments its default uses.
#   argDefaultOrder: names of the arguments with defaults, in the order in which
#     defaults should be evaluated: dependencies first, otherwise left to right.
#
# A default may use other arguments but no other variables, because in C++ it is
# evaluated in the scope of the caller, not the callee (as in R). Function names and
# the left-hand side of `$` (e.g. my_nClass$new()) are not variables.
NF_processArgDefaults <- function(arguments, argSymTab, explicitArgNames = character(),
                                  fnName = "") {
  argNames <- names(arguments)
  Rarguments <- as.list(arguments)
  argDefaults <- list()
  for (nm in argNames) {
    sym <- argSymTab$getSymbol(nm)
    if (!is.null(sym) && isTRUE(sym$hasDefault)) {
      argDefaults[nm] <- list(sym$default)
      Rarguments[nm] <- list(sym$default)
    } else if (!(nm %in% explicitArgNames)) {
      Rarguments[nm] <- list(quote(expr = ))
    }
  }
  argDefaultDeps <- lapply(
    names(argDefaults),
    function(nm) {
      NF_argDefaultDependencies(argDefaults[[nm]], argNames, nm, fnName)
    }
  ) |> structure(names = names(argDefaults))
  argDefaultOrder <- NF_orderArgDefaults(argDefaultDeps, fnName)
  list(
    Rarguments = Rarguments,
    argDefaults = argDefaults,
    argDefaultDeps = argDefaultDeps,
    argDefaultOrder = argDefaultOrder
  )
}

# Find the arguments used in the default for argName, and check
# that it uses no other variables.
NF_argDefaultDependencies <- function(expr, argNames, argName, fnName = "") {
  allowedNames <- c("pi", "Inf", "NaN")
  isBlank <- function(e) identical(e, quote(expr = ))
  findDeps <- function(e) {
    if (is.name(e)) {
      nm <- as.character(e)
      if (nm %in% argNames) {
        return(nm)
      }
      if (nm %in% allowedNames) {
        return(character())
      }
      stop(
        paste0(
          "In nFunction '", fnName, "', the default for argument '", argName,
          "' uses '", nm, "', which is not an argument. ",
          "A default can use other arguments but no other variables."
        ),
        call. = FALSE
      )
    }
    if (!is.call(e)) {
      return(character())
    }
    fn <- e[[1]]
    if (identical(fn, as.name("$"))) {
      # A$b: b is a member name. A is an argument or a class (e.g. my_nClass$new()).
      if (is.name(e[[2]])) {
        lhs <- as.character(e[[2]])
        return(if (lhs %in% argNames) lhs else character())
      }
      return(findDeps(e[[2]]))
    }
    deps <- if (is.name(fn)) character() else findDeps(fn)
    for (i in seq_along(e)[-1]) {
      if (!isBlank(e[[i]])) deps <- c(deps, findDeps(e[[i]]))
    }
    unique(deps)
  }
  if (is.null(expr)) {
    return(character())
  }
  findDeps(expr)
}

# Order the arguments with defaults so that each default is evaluated after
# the defaults of any arguments it uses. Among those ready to be evaluated,
# the left-most comes first. Dependencies on arguments without defaults
# need no ordering, since those arguments must be provided.
NF_orderArgDefaults <- function(argDefaultDeps, fnName = "") {
  remaining <- names(argDefaultDeps)
  ordered <- character()
  while (length(remaining) > 0) {
    ready <- remaining[vapply(
      remaining,
      function(nm) {
        deps <- intersect(argDefaultDeps[[nm]], names(argDefaultDeps))
        all(deps %in% ordered)
      },
      logical(1)
    )]
    if (length(ready) == 0) {
      stop(
        paste0(
          "In nFunction '", fnName, "', the defaults for argument(s) ",
          paste0("'", remaining, "'", collapse = ", "),
          " depend on each other in a cycle."
        ),
        call. = FALSE
      )
    }
    ordered <- c(ordered, ready[1])
    remaining <- setdiff(remaining, ready[1])
  }
  ordered
}
